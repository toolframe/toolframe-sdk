import pytest
from pydantic import ValidationError

from toolframe_sdk import (
    AuthorizationSpec,
    MethodSpec,
    Migration,
    PluginDefinition,
    Principal,
    Resource,
    ScopeSpec,
    ServiceSpec,
    StoreSchema,
    digest,
    validate,
)


def test_definition_round_trip_and_owned_identity():
    definition = PluginDefinition(
        id="example",
        factory="example:Plugin",
        authorization=AuthorizationSpec(
            scopes={"example.read": ScopeSpec(title="Read")}
        ),
        resources=(
            Resource(
                id="main",
                kind="dashboard.page",
                required_scopes=("example.read",),
                data={"entrypoint": "example.ui:render"},
            ),
        ),
    )
    assert (
        PluginDefinition.model_validate_json(definition.model_dump_json()) == definition
    )
    with pytest.raises(ValidationError, match="Duplicate"):
        PluginDefinition(
            id="example",
            factory="example:Plugin",
            authorization=definition.authorization,
            resources=definition.resources * 2,
        )



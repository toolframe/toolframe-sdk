def test_migration_history_and_content_identity():
    first = Migration(revision="one", sql="CREATE TABLE entries(id INTEGER);")
    second = Migration(
        revision="two", parent="one", sql="ALTER TABLE entries ADD COLUMN label TEXT;"
    )
    schema = StoreSchema(revision="two", migrations=(first, second))
    assert len(first.checksum) == 64
    assert digest(schema.model_dump()) != digest(
        schema.model_copy(update={"revision": "other"}).model_dump()
    )
    with pytest.raises(ValidationError, match="linear"):
        StoreSchema(revision="two", migrations=(second, first))


def test_dialect_sql_does_not_rewrite_sqlite_history():
    legacy = Migration(revision="one", sql="CREATE TABLE x(id INTEGER PRIMARY KEY);")
    updated = legacy.model_copy(
        update={
            "dialects": {
                "postgresql": "CREATE TABLE x(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);"
            }
        }
    )
    assert updated.checksum == legacy.checksum
    assert updated.for_dialect("sqlite").checksum == legacy.checksum
    assert updated.for_dialect("postgresql").checksum != legacy.checksum
    assert Migration.model_validate_json(updated.model_dump_json()) == updated
    with pytest.raises(ValueError, match="does not support"):
        legacy.for_dialect("postgresql")


